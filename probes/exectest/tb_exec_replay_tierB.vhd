            case c is
                when '0' => nib := x"0"; when '1' => nib := x"1"; when '2' => nib := x"2"; when '3' => nib := x"3";
                when '4' => nib := x"4"; when '5' => nib := x"5"; when '6' => nib := x"6"; when '7' => nib := x"7";
