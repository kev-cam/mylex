            chk("warp_ctl_if_split", to_std_logic_vector(warp_ctl_if_split), v_warp_ctl_if_split(34 downto 0));
            chk("warp_ctl_if_sjoin", to_std_logic_vector(warp_ctl_if_sjoin), v_warp_ctl_if_sjoin(2 downto 0));
            chk("warp_ctl_if_bar", to_std_logic_vector(warp_ctl_if_bar), v_warp_ctl_if_bar(12 downto 0));
            chk("warp_ctl_if_bar_addr", to_std_logic_vector(warp_ctl_if_bar_addr), v_warp_ctl_if_bar_addr(3 downto 0));
            chk("warp_ctl_if_dvstack_wid", to_std_logic_vector(warp_ctl_if_dvstack_wid), v_warp_ctl_if_dvstack_wid(0 downto 0));
            chk("dcr_csr_if_value", to_std_logic_vector(dcr_csr_if_value), v_dcr_csr_if_value(31 downto 0));
            chk("dcr_csr_if_ready", to_std_logic_vector(dcr_csr_if_ready), v_dcr_csr_if_ready(0 downto 0));
            -- coverage tallies from the NVC DUT's own outputs (a handshake
            -- seen here is consumed by the next rising edge; the ready inputs
            -- are this bench's, driven from the vector at the falling edge)
            if commit_if_0_valid = L3D_1 and commit_if_0_ready = L3D_1 then n_commit0 := n_commit0 + 1; end if;
            if commit_if_1_valid = L3D_1 and commit_if_1_ready = L3D_1 then n_commit1 := n_commit1 + 1; end if;
            if commit_if_2_valid = L3D_1 and commit_if_2_ready = L3D_1 then n_commit2 := n_commit2 + 1; end if;
            if commit_if_3_valid = L3D_1 and commit_if_3_ready = L3D_1 then n_commit3 := n_commit3 + 1; end if;
            if lsu_client_if_0_req_valid = L3D_1 and lsu_client_if_0_req_ready = L3D_1 then n_lsu_req := n_lsu_req + 1; end if;
            if lsu_client_if_0_rsp_valid = L3D_1 and lsu_client_if_0_rsp_ready = L3D_1 then n_lsu_rsp := n_lsu_rsp + 1; end if;
            if branch_ctl_if_0_valid = L3D_1 then n_br := n_br + 1; end if;
            if sched_csr_if_csr_wr_valid = L3D_1 then n_csr_wr := n_csr_wr + 1; end if;
            if sched_csr_if_trap_csr_wr_valid = L3D_1 then n_trap_wr := n_trap_wr + 1; end if;
            if warp_ctl_if_wspawn_valid = L3D_1 or warp_ctl_if_tmc_valid = L3D_1 or warp_ctl_if_split_valid = L3D_1
               or warp_ctl_if_sjoin_valid = L3D_1 or warp_ctl_if_bar_valid = L3D_1 or warp_ctl_if_wsync_valid = L3D_1 then
                n_wctl := n_wctl + 1;
            end if;
            cyc := cyc + 1;
        end loop;
        running <= false;
        if bad = 0 then
            report "PASS: " & integer'image(cyc) & " cycles replayed and compared from cycle 0 (outputs bit-exact, x = don't-care); "
                 & "DUT commits alu/lsu/sfu/fpu="
                 & integer'image(n_commit0) & "/" & integer'image(n_commit1) & "/" & integer'image(n_commit2) & "/" & integer'image(n_commit3)
                 & ", lsu req/rsp=" & integer'image(n_lsu_req) & "/" & integer'image(n_lsu_rsp)
                 & ", branches=" & integer'image(n_br) & ", csr_wr=" & integer'image(n_csr_wr)
                 & ", trap_csr_wr=" & integer'image(n_trap_wr) & ", warp_ctl=" & integer'image(n_wctl)
                 & " -- all outputs identical to the vvp oracle every cycle";
        else
            report "FAIL: " & integer'image(bad) & " output mismatches over " & integer'image(cyc) & " cycles" severity failure;
        end if;
        wait;
    end process;
end architecture;
